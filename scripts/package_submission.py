"""Build only the assignment's explicit deliverables; verification metadata stays local."""
from pathlib import Path,PurePosixPath
import hashlib,json,subprocess,tempfile,zipfile
import nbformat
import pandas as pd
STUDENT='2026aj05073';FOLDER=f'{STUDENT}_DNN_Assignment';OUTPUT=Path(f'{FOLDER}.zip')
REQUIRED=['README.md','requirements.txt','report.pdf','results.csv','problem1/problem1.ipynb',
          'problem2/problem2.ipynb','problem2/generated_samples.txt']
# Required report figures plus the original task figures referenced by notebook text.
FIGURE_NAMES={
 'problem1':['report_class-balance.png','report_confusion.png','report_adding.png',
             'report_sweep-forget.png','report_gradients.png'],
 'problem2':['report_positions.png','report_lm-continued.png','report_attention-heads.png','report_context.png']}
# These nine figures contain every required report panel. Other notebook plots are
# saved in notebook outputs and regenerated by Run All, avoiding duplicate ZIP assets.
files=[Path(p) for p in REQUIRED]
for problem,names in FIGURE_NAMES.items():files += [Path(problem)/'figures'/n for n in names]
files=sorted(files)
assert all(p.is_file() and not p.is_symlink() for p in files),[str(p) for p in files if not p.exists()]
for problem in ('problem1','problem2'):
 n=nbformat.read(f'{problem}/{problem}.ipynb',4);nbformat.validate(n)
 cells=[c for c in n.cells if c.cell_type=='code']
 assert all(c.execution_count is not None for c in cells)
 assert not any(o.output_type=='error' for c in cells for o in c.outputs)
 assert [c.execution_count for c in cells]==list(range(1,len(cells)+1))
ledger=pd.read_csv('results.csv')
assert ledger.columns.tolist()=='problem,model,seed,seq_len,test_acc,macro_f1,test_mse,params,sec_per_epoch,val_loss_nats,bits_per_char,notes'.split(',')
assert len(ledger)==92 and not ledger.duplicated(['problem','model','seed','notes']).any()
assert len(Path('README.md').read_text().split())<=550
info=subprocess.check_output(['pdfinfo','report.pdf'],text=True)
assert 'Pages:           7' in info and '(A4)' in info
manifest={p.as_posix():dict(bytes=p.stat().st_size,sha256=hashlib.sha256(p.read_bytes()).hexdigest()) for p in files}
with zipfile.ZipFile(OUTPUT,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
 for p in files:z.write(p,f'{FOLDER}/{p.as_posix()}')
assert OUTPUT.stat().st_size<=25_000_000
parent=Path('.cache/submission-check');parent.mkdir(parents=True,exist_ok=True)
check=Path(tempfile.mkdtemp(prefix='minimal-',dir=parent))
with zipfile.ZipFile(OUTPUT) as z:
 assert z.testzip() is None
 assert set(z.namelist())=={f'{FOLDER}/{p.as_posix()}' for p in files}
 for name in z.namelist():
  p=PurePosixPath(name);assert not p.is_absolute() and '..' not in p.parts and p.parts[0]==FOLDER
 z.extractall(check)
extracted=check/FOLDER
for name,m in manifest.items():assert hashlib.sha256((extracted/name).read_bytes()).hexdigest()==m['sha256']
record=dict(archive=str(OUTPUT),bytes=OUTPUT.stat().st_size,files=len(files),extraction=str(extracted),
            sha256=hashlib.sha256(OUTPUT.read_bytes()).hexdigest(),crc_passed=True,
            all_file_hashes_passed=True,manifest=manifest)
Path('.cache/submission-verification.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps({k:v for k,v in record.items() if k!='manifest'},indent=2))
